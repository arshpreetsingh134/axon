def test_diff_shows_changes_and_writes_nothing(axon, web_cluster):
    old = bump_traefik_port(web_cluster, 18999)
    before = snapshot(web_cluster.infra)
    r = axon("cluster", "generate", "--diff", cwd=web_cluster.ctrl)
    assert r.code == 0
    assert "~ .axon.infra/fabric/docker-compose.yml" in r.out
    assert re.search(r"^- .*127\.0\.0\.1:%d:%d$" % (old, old), r.out, re.M)
    assert re.search(r"^\+ .*127\.0\.0\.1:18999:18999$", r.out, re.M)
    assert snapshot(web_cluster.infra) == before
    # --check --diff: the diff plus the failing exit code
    r = axon("cluster", "generate", "--check", "--diff", cwd=web_cluster.ctrl)
    assert r.code == 1 and "+ " in r.out


