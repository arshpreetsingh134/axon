def test_generate_migrate_rewrites_a_legacy_clc_member(axon, cluster):
    write(cluster.descriptor, cluster.text() + '\n[[app]]\nname = "acme.clc"\nhost = "console"\ndb   = "clc"\n')
    r = axon("cluster", "generate", "--migrate", cwd=cluster.ctrl)
    assert r.code == 0, r.err
    assert "migrated [[app]] acme.clc → [product.clc]" in r.err
    d = cluster.toml()
    assert "app" not in d
    assert d["product"] == {"clc": {"app": "acme.clc", "host": "console"}}
    before = cluster.text()
    assert axon("cluster", "generate", "--migrate", cwd=cluster.ctrl).code == 0
    assert cluster.text() == before  # idempotent


