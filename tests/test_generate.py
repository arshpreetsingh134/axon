HEADER = "GENERATED by axon from .axon.infra/axonfile — do not edit by hand; run `axon cluster generate`."


def bump_traefik_port(cluster, new_port):
    text = cluster.text()
    port = cluster.toml()["fabric"]["traefik"]["http"]
    write(cluster.descriptor, text.replace("http = %d" % port, "http = %d" % new_port, 1))
    return port


def test_second_generate_is_up_to_date(axon, cluster):
    r = axon("cluster", "generate", cwd=cluster.ctrl)
    assert (r.code, r.out, r.err) == (0, "up to date\n", "")


def test_generate_writes_only_what_changed(axon, web_cluster):
    files = web_cluster.generated_files()
    before = {str(p): os.stat(str(p)).st_mtime_ns for p in files}
    bump_traefik_port(web_cluster, 18999)
    r = axon("cluster", "generate", cwd=web_cluster.ctrl)
    assert r.code == 0
    assert r.out == ""
    assert "  generated .axon.infra/fabric/docker-compose.yml\n" in r.err
    assert "✓ 1 file(s) regenerated" in r.err
    after = {str(p): os.stat(str(p)).st_mtime_ns for p in files}
    changed = [p for p in files if before[str(p)] != after[str(p)]]
    assert changed == [web_cluster.fabric_compose]


def test_check_reports_stale_files_and_writes_nothing(axon, web_cluster):
    bump_traefik_port(web_cluster, 18999)
    before = snapshot(web_cluster.infra)
    r = axon("cluster", "generate", "--check", cwd=web_cluster.ctrl)
    assert r.code == 1
    assert r.out == "~ .axon.infra/fabric/docker-compose.yml\n"
    assert snapshot(web_cluster.infra) == before
    assert axon("cluster", "generate", cwd=web_cluster.ctrl).code == 0
    r = axon("cluster", "generate", "--check", cwd=web_cluster.ctrl)
    assert (r.code, r.out) == (0, "up to date\n")


