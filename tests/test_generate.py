def test_fabric_compose_services_networks_and_ports(web_cluster):
    c = load_yaml(web_cluster.fabric_compose)
    d = web_cluster.toml()
    assert c["name"] == "acme"
    assert c["networks"] == {"shared": {"name": "acme-net", "external": True}}
    assert set(c["services"]) == {"postgres", "temporal", "temporal-ui", "keycloak", "tempo", "grafana", "traefik"}
    assert set(c["volumes"]) == {"pgdata", "tempo-data", "grafana-data"}
    pg = c["services"]["postgres"]
    assert pg["image"] == "postgres:16-alpine"
    assert pg["ports"] == ["127.0.0.1:%d:5432" % d["fabric"]["postgres"]["port"]]
    assert pg["environment"] == {"POSTGRES_USER": "axon", "POSTGRES_PASSWORD": "${POSTGRES_PASSWORD}", "POSTGRES_DB": "postgres"}
    assert pg["networks"]["shared"]["aliases"] == ["postgres"]
    http = d["fabric"]["traefik"]["http"]
    tr = c["services"]["traefik"]
    assert tr["ports"] == ["127.0.0.1:%d:%d" % (http, http)]
    assert "--entrypoints.web.address=:%d" % http in tr["command"]
    aliases = tr["networks"]["shared"]["aliases"]
    assert aliases[0] == "traefik"
    assert set(aliases[1:]) == {"web.lvh.me", "keycloak.lvh.me", "grafana.lvh.me", "temporal.lvh.me"}
    assert c["services"]["temporal"]["environment"]["NUM_HISTORY_SHARDS"] == "128"
    assert c["services"]["keycloak"]["environment"]["KC_HOSTNAME"] == "http://keycloak.lvh.me:%d" % http


