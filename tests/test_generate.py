def test_app_env_reaches_the_stack_and_dollars_are_escaped(axon, cluster):
    r = axon("cluster", "add", "app", "--name", "web", "--from-image", "reg.example/web:1",
             "--env", "PLAIN=hello", "--env", "REF=${API_TOKEN}", "--env", "PRICE=5$", "--env", "BOOL=yes",
             "--env", "NUM=1.0", "--env", "COLON=a: b", cwd=cluster.ctrl)
    assert r.code == 0, r.err
    for svc in load_yaml(cluster.app_compose("web"))["services"].values():
        env = svc["environment"]
        assert env["PLAIN"] == "hello"
        assert env["REF"] == "${API_TOKEN}"  # interpolated by compose from axon's process env
        assert env["PRICE"] == "5$$"  # a literal '$' is escaped for compose
        assert (env["BOOL"], env["NUM"], env["COLON"]) == ("yes", "1.0", "a: b")  # stays a string


