"""Compat mode: axon on an unchanged mycel repo (mycelfile, .mycel.infra/), the axon.toml
overlay, layout precedence, and `axon migrate`."""

import json

import pytest

from _util import load_toml, load_yaml, read, snapshot, tree, write

MYCEL_HEADER = "# GENERATED by axon from .mycel.infra/mycelfile — do not edit by hand; run `axon cluster generate`."


def check_ids(axon, ctrl, *flags):
    r = axon(*(["cluster", "check", "--json"] + list(flags)), cwd=ctrl)
    return r.code, [f["id"] for f in json.loads(r.out)["findings"]]


# ── discovery ────────────────────────────────────────────────────────────────


def test_axon_finds_a_mycel_cluster(axon, mycel_repo):
    code, ids = check_ids(axon, mycel_repo["ctrl"])
    assert code == 0
    assert "COMPAT_MYCEL_LAYOUT" in ids
    assert "CONFORMANCE_APP_NOT_PRESENT" not in ids  # the sibling app resolved through its mycelfile
    assert "SECURITY_DEFAULT_DB_CREDENTIALS" in ids  # compat repos keep mycel's default credentials


def test_compat_check_text(axon, mycel_repo):
    r = axon("cluster", "check", cwd=mycel_repo["ctrl"])
    assert "COMPAT_MYCEL_LAYOUT  .mycel.infra — a mycel repo, used in compat mode (mycel keeps working on it)" in r.out
    assert "repair: axon migrate --apply to switch to axon names" in r.out


