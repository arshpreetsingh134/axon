# ── migrate ──────────────────────────────────────────────────────────────────


def test_migrate_plan_changes_nothing(axon, mycel_overlay):
    ws = mycel_overlay["ws"]
    before = snapshot(ws)
    r = axon("migrate", "--apps", cwd=mycel_overlay["ctrl"])
    assert r.code == 0, r.err
    ctrl = str(mycel_overlay["ctrl"].resolve()) if str(mycel_overlay["ctrl"].resolve()) in r.out else str(mycel_overlay["ctrl"])
    assert r.out.startswith("migration plan for %s:\n" % ctrl)
    assert "/.mycel.infra/mycelfile → axonfile" in r.out
    assert "/shop/mycelfile → axonfile" in r.out
    assert "/.mycel.infra → " in r.out and "/.axon.infra\n" in r.out
    assert "nothing changed — rerun with --apply" in r.out
    assert snapshot(ws) == before


def test_migrate_apply_needs_confirmation(axon, mycel_overlay):
    before = snapshot(mycel_overlay["ws"])
    r = axon("migrate", "--apply", cwd=mycel_overlay["ctrl"])
    assert r.code == 1
    assert r.err == "axon: not migrating without confirmation (pass --yes)\n"
    assert snapshot(mycel_overlay["ws"]) == before


def test_migrate_apply_switches_to_axon_names(axon, mycel_overlay):
    ctrl, ws = mycel_overlay["ctrl"], mycel_overlay["ws"]
    assert axon("cluster", "generate", cwd=ctrl).code == 0  # creates .mycel.infra/.mycel state
    descriptor_before = read(mycel_overlay["infra"] / "mycelfile")
    r = axon("migrate", "--apply", "--yes", "--apps", cwd=ctrl)
    assert r.code == 0, r.err
    assert "to axon names (1 member descriptor(s) renamed)" in r.err
    files = tree(ws)
    assert "x.mycel/.axon.infra/axonfile" in files and "shop/axonfile" in files
    assert "x.mycel/.axon.infra/axon.toml" in files
    assert not any("mycelfile" in f or ".mycel.infra" in f for f in files)
    assert (ctrl / ".axon.infra" / ".axon" / "apps" / "shop").is_dir()  # state dir renamed too
    assert read(ctrl / ".axon.infra" / "axonfile") == descriptor_before  # content untouched
    gi = read(ctrl / ".gitignore")
    for line in (".axon.infra/.env", ".axon.infra/.axon/", ".axon.infra/secrets/*", ".axon.infra/fabric/"):
        assert line in gi.splitlines()
    # axon still works, now natively
    code, ids = check_ids(axon, ctrl)
    assert code == 0 and "COMPAT_MYCEL_LAYOUT" not in ids
    assert "(axon layout)" in axon("cluster", "explain", cwd=ctrl).out
    assert axon("cluster", "generate", cwd=ctrl).code == 0
    assert read(ctrl / ".axon.infra" / "fabric" / "docker-compose.yml").startswith("# GENERATED by axon from .axon.infra/axonfile")
    # and it works with compat off
    assert axon("--compat", "off", "cluster", "check", cwd=ctrl).code == 0
    # a second migrate has nothing to do
    r = axon("migrate", cwd=ctrl)
    assert r.code == 0 and r.out.endswith("already uses axon names\n")


def test_migrate_is_idempotent_on_gitignore(axon, mycel_repo):
    ctrl = mycel_repo["ctrl"]
    write(ctrl / ".gitignore", "# mine\n.axon.infra/.axon/\n")
    assert axon("migrate", "--apply", "-y", cwd=ctrl).code == 0
    assert read(ctrl / ".gitignore") == "# mine\n.axon.infra/.axon/\n"


def test_migrate_keeps_the_database_role_of_existing_data(axon, mycel_repo):
    ctrl = mycel_repo["ctrl"]
    assert axon("cluster", "generate", cwd=ctrl).code == 0
    before = load_yaml(ctrl / ".mycel.infra" / "fabric" / "docker-compose.yml")["services"]["postgres"]["environment"]
