def test_release_workflow_follows_registry_setting(axon, repo_cluster):
    c = repo_cluster
    assert axon("ci", "init", cwd=c.ctrl).code == 0
    rel = c.ctrl / ".github" / "workflows" / "axon-release.yml"
    assert not rel.exists()
    with open(c.infra / "axonfile", "a") as f:
        f.write('\n[release]\nregistry = "ghcr.io/example"\n')
    assert axon("ci", "check", cwd=c.ctrl).code == 1  # the release workflow is now missing
    r = axon("ci", "init", cwd=c.ctrl)
    assert r.code == 0
    text = read(rel)
    assert "axon release create --build --push --registry ghcr.io/example" in text
    assert "AXON_GHCR_TOKEN" in r.out
    assert axon("ci", "check", cwd=c.ctrl).code == 0


def test_release_create_push_needs_a_registry(axon, cluster):
    r = axon("release", "create", "--push", cwd=cluster.ctrl)
    assert r.code == 2 and "--push needs a registry" in r.err


def test_deploy_workflow_and_environments(axon, repo_cluster):
    c = repo_cluster
    with open(c.infra / "axonfile", "a") as f:
        f.write('\n[release]\nregistry = "ghcr.io/example"\nplatforms = ["linux/amd64", "linux/arm64"]\n')
    envs = c.ctrl / "environments"
    envs.mkdir(exist_ok=True)
    (envs / "prod.toml").write_text('name = "prod"\ntier = "prod"\ntarget = "k8s"\n[cloud]\nprovider = "gke"\ncluster = "shop"\n'
                                    'location = "europe-west1"\nproject = "shop-prod"\n'
                                    'workload_identity_provider = "projects/1/locations/global/workloadIdentityPools/gh/providers/gh"\n'
                                    'service_account = "deploy@shop-prod.iam.gserviceaccount.com"\n[ci]\ndeploy = true\nreviewers = ["octocat"]\n')
    r = axon("ci", "init", cwd=c.ctrl)
    assert r.code == 0, r.err
    dep = read(c.ctrl / ".github" / "workflows" / "axon-deploy.yml")
    assert "google-github-actions/get-gke-credentials@v2" in dep and "deploy-prod:" in dep
    assert "environment: prod" in dep and "id-token: write" in dep
    rel = read(c.ctrl / ".github" / "workflows" / "axon-release.yml")
    assert "docker/setup-qemu-action@v3" in rel
    assert "prod · reviewers octocat" in r.out and "axon ci environments --apply" in r.out
    assert axon("ci", "check", cwd=c.ctrl).code == 0
    # an incomplete [cloud] is rejected
    (envs / "prod.toml").write_text('name = "prod"\n[cloud]\nprovider = "aks"\n[ci]\ndeploy = true\n')
    r = axon("ci", "check", cwd=c.ctrl)
    assert r.code != 0 and "environments/prod.toml" in r.err


def test_release_create_multi_arch_needs_build_and_push(axon, cluster):
    r = axon("release", "create", "--platform", "linux/amd64,linux/arm64", "--registry", "ghcr.io/x", cwd=cluster.ctrl)
    assert r.code == 2 and "--build --push" in r.err
    r = axon("release", "create", "--platform", "windows/amd64", cwd=cluster.ctrl)
    assert r.code == 2 and "want linux/<arch>" in r.err
