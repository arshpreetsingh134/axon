"""axon ci init / ci check: pipeline generation and drift detection (offline)."""
import os
import subprocess

import pytest

from _util import read

GIT_ENV = {"GIT_AUTHOR_NAME": "t", "GIT_AUTHOR_EMAIL": "t@t", "GIT_COMMITTER_NAME": "t", "GIT_COMMITTER_EMAIL": "t@t",
           "GIT_CONFIG_GLOBAL": "/dev/null", "GIT_CONFIG_NOSYSTEM": "1"}


def git(cwd, *args):
    env = dict(os.environ, **GIT_ENV)
    subprocess.run(["git", "-C", str(cwd), *args], check=True, capture_output=True, env=env)


def commit_all(d):
    git(d, "add", "-A")
    git(d, "commit", "-q", "-m", "x", "--allow-empty")


@pytest.fixture
def repo_cluster(axon, cluster):
    """The shared cluster fixture made into a git repo, with a member app in its own repo."""
    git(cluster.ctrl, "init", "-q", "-b", "main")
    commit_all(cluster.ctrl)
    return cluster


def workflow(c):
    return c.ctrl / ".github" / "workflows" / "axon-ci.yml"


def test_ci_init_outside_git_fails(axon, cluster):
    r = axon("ci", "init", cwd=cluster.ctrl)
    assert r.code == 1 and "not inside a git repository" in r.err


def test_ci_init_writes_workflow_and_ci_env(axon, repo_cluster):
    c = repo_cluster
    r = axon("ci", "init", cwd=c.ctrl)
    assert r.code == 0, r.err
    text = read(workflow(c))
    assert text.startswith("# GENERATED by `axon ci init`")
    assert "axon ci check" in text and "axon env test ci" in text
    assert (c.ctrl / "environments" / "ci.toml").exists()
    assert 'target    = "docker"' in read(c.ctrl / "environments" / "ci.toml")
    assert axon("ci", "check", cwd=c.ctrl).out.strip() == "up to date"


def test_ci_init_dry_run_writes_nothing(axon, repo_cluster):
    c = repo_cluster
    r = axon("ci", "init", "--dry-run", cwd=c.ctrl)
    assert r.code == 0 and "would write" in r.out
    assert not workflow(c).exists()
    assert not (c.ctrl / "environments" / "ci.toml").exists()


def test_ci_check_reports_missing_and_drift(axon, repo_cluster):
    c = repo_cluster
    r = axon("ci", "check", cwd=c.ctrl)
    assert r.code == 1 and "is missing" in r.out
    assert axon("ci", "init", cwd=c.ctrl).code == 0
    desc = c.infra / "axonfile"
    with open(desc, "a") as f:
        f.write('\n[ci]\nbranches = ["develop"]\n')
    r = axon("ci", "check", "--diff", cwd=c.ctrl)
    assert r.code == 1 and "out of date" in r.out and "+       - develop" in r.out
    assert axon("ci", "init", cwd=c.ctrl).code == 0
    assert axon("ci", "check", cwd=c.ctrl).code == 0


def test_ci_init_detects_member_repo(axon, repo_cluster, tmp_path):
    c = repo_cluster
    member = c.ctrl.parent / "shop.web"
    member.mkdir()
    (member / "axonfile").write_text('build_type = "project"\n[app]\nname = "shop.web"\n[[project.build]]\nname = "x"\ncommand = "true"\n')
    git(member, "init", "-q", "-b", "trunk")
    commit_all(member)
    git(member, "remote", "add", "origin", "git@github.com:example/shop-web.git")
    with open(c.infra / "axonfile", "a") as f:
        f.write('\n[[app]]\nname = "shop.web"\nkind = "project"\n')
    r = axon("ci", "init", cwd=c.ctrl)
    assert r.code == 0, r.err
    assert "checkout shop.web → example/shop-web@trunk" in r.err
    ov = read(c.infra / "axon.toml")
    assert "[ci.checkouts]" in ov and '"shop.web" = "example/shop-web@trunk"' in ov
    assert "[ci.links]" not in ov  # the app dir is the repo itself
    text = read(workflow(c))
    assert "repository: example/shop-web" in text and "ref: trunk" in text and "path: shop.web" in text
    assert "AXON_REPOS_TOKEN" in r.out
    # recorded once: a second init does not re-detect
    git(member, "checkout", "-q", "-b", "other")
    assert axon("ci", "init", cwd=c.ctrl).code == 0
    assert '"shop.web" = "example/shop-web@trunk"' in read(c.infra / "axon.toml")
    assert axon("ci", "check", cwd=c.ctrl).code == 0


def test_ci_init_links_symlinked_member_app(axon, repo_cluster, tmp_path):
    """A member app that is a symlink into another checkout: the repo is checked out, the app linked."""
    c = repo_cluster
    mono = tmp_path / "elsewhere" / "mono"
    app = mono / "apps" / "shop.api"
    app.mkdir(parents=True)
    (app / "axonfile").write_text('build_type = "project"\n[app]\nname = "shop.api"\n[[project.build]]\nname = "x"\ncommand = "true"\n')
    git(mono, "init", "-q", "-b", "main")
    commit_all(mono)
    git(mono, "remote", "add", "origin", "https://github.com/example/mono.git")
    (c.ctrl.parent / "shop.api").symlink_to(app)
    with open(c.infra / "axonfile", "a") as f:
        f.write('\n[[app]]\nname = "shop.api"\nkind = "project"\n')
    r = axon("ci", "init", cwd=c.ctrl)
    assert r.code == 0, r.err
    ov = read(c.infra / "axon.toml")
    assert '".axon-ci/example__mono" = "example/mono@main"' in ov
    assert '"shop.api" = ".axon-ci/example__mono/apps/shop.api"' in ov
    text = read(workflow(c))
    assert 'ln -sfn "$GITHUB_WORKSPACE/.axon-ci/example__mono/apps/shop.api" "$GITHUB_WORKSPACE/shop.api"' in text


def test_ci_init_lists_secrets(axon, repo_cluster):
    c = repo_cluster
