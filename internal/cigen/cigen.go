// Package cigen generates the GitHub Actions pipelines of an axon project from its
// descriptor, [ci]/[release] settings and environment files. Generation is
// deterministic (it reads only committed configuration, never the local machine's
// git state), so `axon ci check` gives the same answer on a laptop and inside CI.
package cigen

import (
	"fmt"
	"os"
	"path"
	"path/filepath"
	"sort"
	"strings"

	"axon/internal/descriptor"
	"axon/internal/envcfg"
	"axon/internal/gen"
	y "axon/internal/yamlx"
)

// DefaultAxonRepo is where axon releases are published.
const DefaultAxonRepo = "arshpreetsingh134/axon"

// Workflow files, relative to the repository root.
const (
	WorkflowPath        = ".github/workflows/axon-ci.yml"
	ReleaseWorkflowPath = ".github/workflows/axon-release.yml"
	DeployWorkflowPath  = ".github/workflows/axon-deploy.yml"
)

// Layout places the project inside its git repository.
type Layout struct {
	RepoBase string // checkout dir name of the controller repo (basename of its top level)
	CtrlRel  string // controller dir relative to the repo top level ("." when it is the top)
}

// Checkout is one more repository the project is assembled from.
type Checkout struct {
	Path string // workspace-relative
	Repo string // owner/name
	Ref  string // branch or tag ("" = default branch)
}

// ParseCheckout parses a [ci.checkouts] entry: path = "owner/repo[@ref]".
func ParseCheckout(p, spec string) (Checkout, error) {
	c := Checkout{Path: strings.Trim(filepath.ToSlash(p), "/")}
	s := spec
	if i := strings.Index(s, "@"); i >= 0 {
		c.Ref, s = s[i+1:], s[:i]
	}
	if strings.Count(s, "/") != 1 || strings.HasPrefix(s, "/") || strings.HasSuffix(s, "/") {
		return c, fmt.Errorf("[ci.checkouts] %q = %q: want \"owner/repo[@ref]\"", p, spec)
	}
	if c.Path == "" || c.Path == "." || strings.HasPrefix(c.Path, "..") || path.IsAbs(c.Path) {
		return c, fmt.Errorf("[ci.checkouts] %q: the path must be inside the workspace", p)
	}
	c.Repo = s
	return c, nil
}

// Spec renders "owner/repo[@ref]".
func (c Checkout) Spec() string {
	if c.Ref != "" {
		return c.Repo + "@" + c.Ref
	}
	return c.Repo
}

// Result is a generated pipeline set.
type Result struct {
	Files      map[string]string   // repo-relative path → content
	Secrets    []string            // repository secrets the pipelines read
	Optional   []string            // repository secrets used only when present
	EnvSecrets map[string][]string // environment → secrets of that GitHub Environment
	Envs       []DeployEnv         // environments the deploy pipeline targets
	Warnings   []string
}

// DeployEnv is an environment deployed from CI (a GitHub Environment).
type DeployEnv struct {
	Name         string
	Reviewers    []string
	WaitMinutes  int
	Branches     []string
	PromotesFrom string
	Auto         bool
	URL          string
}

func boolOr(p *bool, d bool) bool {
	if p == nil {
		return d
	}
	return *p
}

// derived values are generated by axon itself; CI needs no secret for them.
func derived(v string) bool {
	switch v {
	case "POSTGRES_PASSWORD", "IAM_SIGNING_KEY", "OIDC_CLIENT_SECRET", "KEYCLOAK_ADMIN_PASSWORD":
		return true
	}
	return strings.HasSuffix(v, "_CLICKHOUSE_WRITER_PASSWORD") || strings.HasSuffix(v, "_CLICKHOUSE_READER_PASSWORD")
}

type gctx struct {
	m         *descriptor.Model
	cfg       descriptor.CIConfig
	lay       Layout
	ctrlPath  string // controller dir, relative to $GITHUB_WORKSPACE
	wsPath    string // workspace root (the controller's parent), relative to $GITHUB_WORKSPACE
	checkouts []Checkout
	links     [][2]string
	needGo    bool
	needNode  bool
	ghcr      bool // private ghcr.io images are pulled
	runner    string
	axonRepo  string
	axonVer   string
	secrets   []string
	registry  string
	regHost   string
	platforms []string
}

func (g *gctx) ws(rel string) string { return path.Clean(path.Join(g.wsPath, rel)) }

func (g *gctx) checkoutSteps(ctrlRef string, fullHistory bool) []any {
	with := y.New("path", g.lay.RepoBase)
	if ctrlRef != "" {
		with.Set("ref", ctrlRef)
	}
	steps := []any{y.New("name", "Check out "+g.lay.RepoBase, "uses", "actions/checkout@v5", "with", with)}
	for _, c := range g.checkouts {
		w := y.New("repository", c.Repo, "path", g.ws(c.Path), "token", "${{ secrets.AXON_REPOS_TOKEN || github.token }}")
		if c.Ref != "" {
			w.Set("ref", c.Ref)
		}
		if fullHistory {
			w.Set("fetch-depth", 0)
		}
		steps = append(steps, y.New("name", "Check out "+c.Path, "uses", "actions/checkout@v5", "with", w))
	}
	if len(g.links) > 0 {
		var cmds []string
		for _, l := range g.links {
			link, target := g.ws(l[0]), g.ws(l[1])
			ln := fmt.Sprintf("ln -sfn \"$GITHUB_WORKSPACE/%s\" \"$GITHUB_WORKSPACE/%s\"", target, link)
			if dir := path.Dir(link); dir != "." {
				ln = fmt.Sprintf("mkdir -p \"$GITHUB_WORKSPACE/%s\" && %s", dir, ln)
			}
			cmds = append(cmds, ln)
		}
		steps = append(steps, y.New("name", "Link member apps", "run", strings.Join(cmds, "\n")))
	}
	return steps
}

func (g *gctx) toolSteps(toolchains bool) []any {
	steps := []any{y.New("name", "Install axon",
		"env", y.New("AXON_REPO", g.axonRepo, "AXON_VERSION", g.axonVer, "GH_TOKEN", "${{ github.token }}"),
		"run", installScript)}
	if toolchains && g.needGo {
		steps = append(steps, y.New("uses", "actions/setup-go@v6", "with", y.New("go-version", "stable", "cache", false)))
	}
	if toolchains && g.needNode {
		steps = append(steps, y.New("uses", "actions/setup-node@v5", "with", y.New("node-version", "20")))
	}
	return steps
}

func (g *gctx) ghcrLogin() any {
	return y.New("name", "Log in to ghcr.io", "uses", "docker/login-action@v3",
		"with", y.New("registry", "ghcr.io", "username", "${{ github.actor }}", "password", "${{ secrets.AXON_GHCR_TOKEN || github.token }}"))
}

// secretEnv is the step env carrying every deploy secret (plus extra key/value pairs).
func (g *gctx) secretEnv(extra ...string) any {
	m := y.New()
	for i := 0; i+1 < len(extra); i += 2 {
		m.Set(extra[i], extra[i+1])
	}
	for _, s := range g.secrets {
		m.Set(s, "${{ secrets."+s+" }}")
	}
	if m.Len() == 0 {
		return nil
	}
	return m
}

// Generate renders every pipeline the configuration asks for.
func Generate(m *descriptor.Model, lay Layout) (*Result, error) {
	cfg := m.C.CI
	if cfg.Provider != "" && cfg.Provider != "github" {
		return nil, fmt.Errorf("[ci] provider %q is not supported yet (github)", cfg.Provider)
	}
	res := &Result{Files: map[string]string{}, EnvSecrets: map[string][]string{}}
	g := &gctx{m: m, cfg: cfg, lay: lay, runner: or(cfg.Runner, "ubuntu-latest"),
		axonRepo: or(cfg.AxonRepo, DefaultAxonRepo), axonVer: or(cfg.AxonVersion, "latest")}
	g.ctrlPath = path.Clean(path.Join(lay.RepoBase, filepath.ToSlash(lay.CtrlRel)))
	g.wsPath = path.Dir(g.ctrlPath)
	g.registry = strings.TrimSuffix(m.C.Release.Registry, "/")
	g.regHost = strings.SplitN(g.registry, "/", 2)[0]
	g.platforms = m.C.Release.Platforms

	for _, p := range sortedKeys(cfg.Checkouts) {
		c, err := ParseCheckout(p, cfg.Checkouts[p])
		if err != nil {
			return nil, err
		}
		g.checkouts = append(g.checkouts, c)
	}
	for _, l := range sortedKeys(cfg.Links) {
		link, target := strings.Trim(filepath.ToSlash(l), "/"), strings.Trim(filepath.ToSlash(cfg.Links[l]), "/")
		if link == "" || target == "" || strings.HasPrefix(link, "..") || strings.HasPrefix(target, "..") {
			return nil, fmt.Errorf("[ci.links] %q = %q: both sides must be workspace-relative paths", l, cfg.Links[l])
		}
		g.links = append(g.links, [2]string{link, target})
	}

	in := &gen.Input{M: m, Target: "docker", PG: gen.PG{Host: "postgres", Port: 5432, User: gen.PGUser(m), Password: "${POSTGRES_PASSWORD}"}}
	for _, v := range in.SecretVars() {
		if !derived(v) {
			g.secrets = append(g.secrets, v)
		}
	}
	sort.Strings(g.secrets)
	res.Secrets = append(res.Secrets, g.secrets...)

	for _, a := range m.Apps {
		for _, mod := range a.Modules {
			if mod.IsImage() {
				g.ghcr = g.ghcr || strings.HasPrefix(mod.Image, "ghcr.io/")
				continue
			}
			if mod.Lang == "go" || mod.Lang == "" {
				g.needGo = true
			}
			if mod.SrcDir != "" {
				if _, err := os.Stat(filepath.Join(mod.SrcDir, "ui", "package.json")); err == nil {
					g.needNode = true
				}
			}
		}
		g.ghcr = g.ghcr || strings.HasPrefix(a.Decl.Image, "ghcr.io/")
	}
	g.ghcr = g.ghcr || strings.HasPrefix(m.SubstImage(m.C.CoreImage), "ghcr.io/")
	if len(g.checkouts) > 0 {
		res.Optional = append(res.Optional, "AXON_REPOS_TOKEN")
	}
	if g.ghcr || g.regHost == "ghcr.io" {
		res.Optional = append(res.Optional, "AXON_GHCR_TOKEN")
	}
	if g.registry != "" && g.regHost != "ghcr.io" {
		res.Secrets = append(res.Secrets, "AXON_REGISTRY_USERNAME", "AXON_REGISTRY_PASSWORD")
	}
	sort.Strings(res.Secrets)

	header := fmt.Sprintf("# GENERATED by `axon ci init` from %s/%s — do not edit by hand.\n"+
		"# Change [ci]/[release] in the descriptor or axon.toml (or [cloud]/[ci] in environments/*.toml),\n"+
		"# then rerun `axon ci init`; `axon ci check` reports drift.\n", m.L.Infra, m.L.File)
	if err := g.ciWorkflow(res, header); err != nil {
		return nil, err
	}
	if g.registry != "" {
		if err := g.releaseWorkflow(res, header); err != nil {
			return nil, err
		}
	} else if len(g.platforms) > 0 {
		res.Warnings = append(res.Warnings, "[release] platforms has no effect without [release] registry")
	}
	if err := g.deployWorkflow(res, header); err != nil {
		return nil, err
	}
	g.warnings(res)
	return res, nil
}

func (g *gctx) ciWorkflow(res *Result, header string) error {
	cfg := g.cfg
	env := or(cfg.Env, "ci")
	branches := cfg.Branches
	if len(branches) == 0 {
		branches = []string{"main"}
	}
	check := append(g.checkoutSteps("", false), g.toolSteps(true)...)
	check = append(check,
		y.New("name", "Pipeline is up to date", "working-directory", g.ctrlPath, "run", "axon ci check"),
		y.New("name", "Cluster check", "working-directory", g.ctrlPath, "run", "axon cluster check"),
		y.New("name", "Environment check", "working-directory", g.ctrlPath, "env", g.secretEnv(), "run", "axon env check "+env),
	)
	if boolOr(cfg.AppTests, true) {
		for _, a := range g.m.Apps {
			src := false
			for _, mod := range a.Modules {
				src = src || !mod.IsImage()
			}
			if a.Decl.Cored() && src {
				check = append(check, y.New("name", "Unit tests: "+a.Decl.Name, "working-directory", g.ws(a.Decl.Name), "run", "axon app test"))
			}
		}
	}
	jobs := y.New("check", y.New("name", "check", "runs-on", g.runner, "timeout-minutes", 30, "steps", check))
	if boolOr(cfg.E2E, true) {
		up := "axon up --build --env " + env + " --target docker --timeout " + or(cfg.Timeout, "20m")
		for _, a := range cfg.Apps {
			up += " --app " + a
		}
		if !boolOr(cfg.Hooks, true) {
			up += " --no-hooks"
		}
		e2e := append(g.checkoutSteps("", false), g.toolSteps(true)...)
		if g.ghcr {
			e2e = append(e2e, g.ghcrLogin())
		}
		e2e = append(e2e,
			y.New("name", "Deploy the stack", "working-directory", g.ctrlPath, "env", g.secretEnv(), "run", up),
			y.New("name", "Journeys and health probes", "working-directory", g.ctrlPath, "env", g.secretEnv(), "run", "axon env test "+env),
			y.New("name", "Diagnose", "if", "failure()", "working-directory", g.ctrlPath,
				"run", "axon env status "+env+" || true\naxon env diagnose "+env+" || true\nfor a in $(docker ps --format '{{.Names}}'); do echo \"::group::$a\"; docker logs --tail 80 \"$a\" 2>&1 || true; echo '::endgroup::'; done"),
			y.New("name", "Tear down", "if", "always()", "working-directory", g.ctrlPath, "run", "axon down --env "+env+" --volumes --yes || true"),
		)
		jobs.Set("e2e", y.New("name", "e2e", "needs", "check", "runs-on", g.runner, "timeout-minutes", 90, "steps", e2e))
	}
	var br []any
	for _, b := range branches {
		br = append(br, b)
	}
	return render(res, WorkflowPath, header, y.New(
		"name", "axon-ci",
		"on", y.New("push", y.New("branches", br), "pull_request", y.New(), "workflow_dispatch", y.New()),
		"concurrency", y.New("group", "axon-ci-${{ github.ref }}", "cancel-in-progress", true),
		"permissions", y.New("contents", "read", "packages", "read"),
		"jobs", jobs,
	))
}

func (g *gctx) releaseWorkflow(res *Result, header string) error {
	steps := append(g.checkoutSteps("", false), g.toolSteps(true)...)
	if len(g.platforms) > 1 {
		steps = append(steps,
			y.New("name", "Set up QEMU (multi-architecture images)", "uses", "docker/setup-qemu-action@v3"),
			y.New("name", "Set up Docker Buildx", "uses", "docker/setup-buildx-action@v3"))
	}
	login := y.New("registry", g.regHost, "username", "${{ github.actor }}", "password", "${{ secrets.AXON_GHCR_TOKEN || github.token }}")
	if g.regHost != "ghcr.io" {
		login = y.New("registry", g.regHost, "username", "${{ secrets.AXON_REGISTRY_USERNAME }}", "password", "${{ secrets.AXON_REGISTRY_PASSWORD }}")
	}
	steps = append(steps, y.New("name", "Log in to "+g.regHost, "uses", "docker/login-action@v3", "with", login))
	if g.ghcr && g.regHost != "ghcr.io" {
		steps = append(steps, g.ghcrLogin())
	}
	create := `axon release create --build --push --registry ` + g.registry + ` --version "${GITHUB_REF_NAME#v}"`
	if !boolOr(g.cfg.Hooks, true) {
		create += " --no-hooks"
	}
	steps = append(steps,
		y.New("name", "Build, push and record the release", "working-directory", g.ctrlPath, "run", create),
		y.New("name", "Attach the release record to the GitHub Release", "working-directory", g.ctrlPath,
			"env", y.New("GH_TOKEN", "${{ github.token }}"),
			"run", "v=\"${GITHUB_REF_NAME#v}\"\n"+
				"gh release view \"$GITHUB_REF_NAME\" --repo \"$GITHUB_REPOSITORY\" >/dev/null 2>&1 || gh release create \"$GITHUB_REF_NAME\" --repo \"$GITHUB_REPOSITORY\" --title \"$GITHUB_REF_NAME\" --generate-notes\n"+
				"gh release upload \"$GITHUB_REF_NAME\" \"releases/$v.toml\" --repo \"$GITHUB_REPOSITORY\" --clobber"),
		y.New("name", "Keep the release record", "uses", "actions/upload-artifact@v4",
			"with", y.New("name", "release-record", "path", g.ctrlPath+"/releases/*.toml")),
	)
	return render(res, ReleaseWorkflowPath, header, y.New(
		"name", "axon-release",
		"on", y.New("push", y.New("tags", []any{"v*"})),
		"concurrency", y.New("group", "axon-release-${{ github.ref }}", "cancel-in-progress", false),
		"permissions", y.New("contents", "write", "packages", "write"),
		"jobs", y.New("release", y.New("name", "release", "runs-on", g.runner, "timeout-minutes", 120, "steps", steps)),
	))
}

// JobID is the deploy job of an environment.
func JobID(env string) string {
	var b strings.Builder
	for _, r := range env {
		if r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || r == '-' || r == '_' {
			b.WriteRune(r)
		} else {
			b.WriteRune('-')
		}
	}
	return "deploy-" + b.String()
}

func (g *gctx) deployWorkflow(res *Result, header string) error {
	names, err := envcfg.List(g.m.Dir)
	if err != nil {
		return err
	}
	var envs []*envcfg.Env
	byName := map[string]bool{}
	for _, n := range names {
		e, err := envcfg.Load(g.m.Dir, g.m.C.Name, n)
		if err != nil {
			return err
		}
		if !e.CI.Deploy {
			continue
		}
		if err := e.Cloud.Validate(); err != nil {
			return fmt.Errorf("environments/%s.toml: %w", n, err)
		}
		envs = append(envs, e)
		byName[n] = true
	}
	if len(envs) == 0 {
		return nil
	}
	if g.registry == "" {
		return fmt.Errorf("environments with [ci] deploy = true need [release] registry: the cluster pulls release images from it")
	}
	var options []any
	for _, e := range envs {
		options = append(options, e.Name)
	}
	pullUser, pullPass := "${{ github.actor }}", "${{ secrets.AXON_GHCR_TOKEN || github.token }}"
	if g.regHost != "ghcr.io" {
		pullUser, pullPass = "${{ secrets.AXON_REGISTRY_USERNAME }}", "${{ secrets.AXON_REGISTRY_PASSWORD }}"
	}
	timeout := or(g.cfg.Timeout, "20m")
	tagExpr := "${{ github.event_name == 'workflow_dispatch' && (startsWith(inputs.version, 'v') && inputs.version || format('v{0}', inputs.version)) || github.event.workflow_run.head_branch }}"
	jobs := y.New()
	for _, e := range envs {
		needs := ""
		if e.PromotesFrom != "" && byName[e.PromotesFrom] {
			needs = JobID(e.PromotesFrom)
		}
		chain := "false"
		switch {
		case e.CI.Auto:
			chain = "true"
		case needs != "":
			chain = "needs." + needs + ".result == 'success'"
		}
		cond := fmt.Sprintf("${{ always() && ((github.event_name == 'workflow_dispatch' && inputs.environment == '%s') || "+
			"(github.event_name == 'workflow_run' && github.event.workflow_run.conclusion == 'success' && %s)) }}", e.Name, chain)

		ctx := `--context "$(kubectl config current-context)"`
		deploy := fmt.Sprintf(`axon env deploy %s "${AXON_TAG#v}" --target k8s %s --timeout %s --yes`, e.Name, ctx, timeout)
		if !boolOr(g.cfg.Hooks, true) {
			deploy += " --no-hooks"
		}
		test := "axon env test " + e.Name
		if domain := or(e.Domain, g.m.C.Domain); domain == "" || domain == "localhost" || strings.HasSuffix(domain, ".localhost") {
			// a local-only domain: reach the front door through a port-forward
			port := g.m.C.HTTPPort()
			if e.HTTPPort > 0 {
				port = e.HTTPPort
			}
			test = fmt.Sprintf("kubectl -n %s port-forward svc/traefik %d:%d >/tmp/port-forward.log 2>&1 &\npf=$!\ntrap 'kill $pf' EXIT\n"+
				"for i in $(seq 30); do nc -z 127.0.0.1 %d && break; sleep 1; done\n%s", e.Namespace, port, port, port, test)
		}

		steps := append(g.checkoutSteps("${{ env.AXON_TAG }}", true), g.toolSteps(false)...)
		steps = append(steps, g.cloudSteps(e, res)...)
		steps = append(steps,
			y.New("name", "Fetch the release record", "working-directory", g.ctrlPath, "env", y.New("GH_TOKEN", "${{ github.token }}"),
				"run", "v=\"${AXON_TAG#v}\"\nmkdir -p releases\ngh release download \"$AXON_TAG\" --repo \"$GITHUB_REPOSITORY\" --pattern \"$v.toml\" --dir releases --clobber"),
			y.New("name", "Pin the released source commits", "working-directory", g.ctrlPath, "run", `axon release checkout "${AXON_TAG#v}"`),
			y.New("name", "Deploy "+e.Name, "working-directory", g.ctrlPath,
				"env", g.secretEnv("AXON_PULL_REGISTRY", g.regHost, "AXON_PULL_USERNAME", pullUser, "AXON_PULL_PASSWORD", pullPass),
				"run", deploy),
			y.New("name", "Journeys and health probes", "working-directory", g.ctrlPath, "env", g.secretEnv(), "run", test),
			y.New("name", "Diagnose", "if", "failure()", "working-directory", g.ctrlPath,
				"run", fmt.Sprintf("axon env status %s --target k8s %s || true\nkubectl -n %s get pods -o wide || true\nkubectl -n %s get events --sort-by=.lastTimestamp | tail -40 || true",
					e.Name, ctx, e.Namespace, e.Namespace)),
		)
		envBlock := any(e.Name)
		if e.CI.URL != "" {
			envBlock = y.New("name", e.Name, "url", e.CI.URL)
		}
		job := y.New("name", "deploy "+e.Name)
		if needs != "" {
			job.Set("needs", needs)
		}
		job.Set("if", cond)
		job.Set("runs-on", g.runner)
		job.Set("environment", envBlock)
		job.Set("timeout-minutes", 60)
		job.Set("env", y.New("AXON_TAG", tagExpr))
		job.Set("steps", steps)
		jobs.Set(JobID(e.Name), job)
		res.Envs = append(res.Envs, DeployEnv{Name: e.Name, Reviewers: e.CI.Reviewers, WaitMinutes: e.CI.WaitMinutes,
			Branches: e.CI.Branches, PromotesFrom: e.PromotesFrom, Auto: e.CI.Auto, URL: e.CI.URL})
	}
	return render(res, DeployWorkflowPath, header, y.New(
		"name", "axon-deploy",
		"on", y.New(
			"workflow_run", y.New("workflows", []any{"axon-release"}, "types", []any{"completed"}),
			"workflow_dispatch", y.New("inputs", y.New(
				"environment", y.New("description", "environment to deploy", "required", true, "type", "choice", "options", options),
				"version", y.New("description", "release version, e.g. 0.1.2", "required", true, "type", "string"),
			)),
		),
		"concurrency", y.New("group", "axon-deploy-${{ inputs.environment || github.event.workflow_run.head_branch }}", "cancel-in-progress", false),
		"permissions", y.New("contents", "read", "packages", "read", "id-token", "write"),
		"jobs", jobs,
	))
}

// cloudSteps logs in to the environment's cloud (OIDC, no long-lived keys) and selects its cluster.
func (g *gctx) cloudSteps(e *envcfg.Env, res *Result) []any {
	c := e.Cloud
	switch c.Provider {
	case "eks":
		return []any{
			y.New("name", "Log in to AWS", "uses", "aws-actions/configure-aws-credentials@v4",
				"with", y.New("role-to-assume", c.RoleARN, "aws-region", c.Region)),
			y.New("name", "Select the EKS cluster", "run", fmt.Sprintf("aws eks update-kubeconfig --name %s --region %s", c.Cluster, c.Region)),
		}
	case "gke":
		return []any{
			y.New("name", "Log in to Google Cloud", "uses", "google-github-actions/auth@v2",
				"with", y.New("workload_identity_provider", c.WorkloadIdentityProvider, "service_account", c.ServiceAccount)),
			y.New("name", "Select the GKE cluster", "uses", "google-github-actions/get-gke-credentials@v2",
				"with", y.New("cluster_name", c.Cluster, "location", c.Location, "project_id", c.Project)),
		}
	case "aks":
		return []any{
			y.New("name", "Log in to Azure", "uses", "azure/login@v2",
				"with", y.New("client-id", c.ClientID, "tenant-id", c.TenantID, "subscription-id", c.SubscriptionID)),
			y.New("name", "Select the AKS cluster", "uses", "azure/aks-set-context@v4",
				"with", y.New("resource-group", c.ResourceGroup, "cluster-name", c.Cluster)),
		}
	default: // kubeconfig: an Environment secret holding the whole file
		res.EnvSecrets[e.Name] = append(res.EnvSecrets[e.Name], "KUBECONFIG")
		return []any{y.New("name", "Write the kubeconfig", "env", y.New("KUBECONFIG_DATA", "${{ secrets.KUBECONFIG }}"),
			"run", "mkdir -p ~/.kube\nprintf '%s' \"$KUBECONFIG_DATA\" > ~/.kube/config\nchmod 600 ~/.kube/config\nkubectl config current-context")}
	}
}

func (g *gctx) warnings(res *Result) {
	m := g.m
	root, _ := filepath.EvalSymlinks(m.Root)
	ctrl, _ := filepath.EvalSymlinks(m.Dir)
	sep := string(filepath.Separator)
	covered := func(real string) bool {
		if real == ctrl || strings.HasPrefix(real, ctrl+sep) {
			return true
		}
		rel, err := filepath.Rel(root, real)
		if err != nil {
			return false
		}
		rel = filepath.ToSlash(rel)
		for _, c := range g.checkouts {
			if rel == c.Path || strings.HasPrefix(rel, c.Path+"/") {
				return true
			}
		}
		return false
	}
	for _, a := range m.Apps {
		if a.File == nil || a.Dir == "" {
			continue
		}
		if r, err := filepath.EvalSymlinks(a.Dir); err == nil && !covered(r) {
			res.Warnings = append(res.Warnings, fmt.Sprintf("%s (%s) is in no checkout; CI will not have it — `axon ci init --redetect` records its repository", a.Decl.Name, r))
			continue
		}
		for _, mod := range a.Modules {
			if mod.SrcDir == "" {
				continue
			}
			if r, err := filepath.EvalSymlinks(mod.SrcDir); err == nil && !covered(r) {
				res.Warnings = append(res.Warnings, fmt.Sprintf("%s: module %s (%s) is in no checkout", a.Decl.Name, mod.Token, r))
			}
		}
	}
	if len(m.C.Hooks.PreBuild)+len(m.C.Hooks.PostDeploy)+len(m.C.Hooks.PostFabric) > 0 && boolOr(g.cfg.Hooks, true) {
		res.Warnings = append(res.Warnings, "lifecycle hooks run in CI too; set [ci] hooks = false if they need things only your machine has")
	}
}

func render(res *Result, file, header string, doc *y.M) error {
	body, err := y.Marshal(doc)
	if err != nil {
		return err
	}
	res.Files[file] = header + body
	return nil
}

func or(a, b string) string {
	if a == "" {
		return b
	}
	return a
}

func sortedKeys(m map[string]string) []string {
	var ks []string
	for k := range m {
		ks = append(ks, k)
	}
	sort.Strings(ks)
	return ks
}

